import sys
from PIL import Image
base=sys.argv[1]
s=2550/2184
def run(img,items):
    im=Image.open(base+'/scans/'+img)
    for name,box in items:
        b=[int(v*s) for v in box]
        r=im.crop(b); r=r.resize((r.width*2,r.height*2)); r.save(base+'/work/crops/'+name)
