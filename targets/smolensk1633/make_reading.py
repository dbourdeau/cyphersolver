"""Build reading.tsv: one row per cipher word with the raw decipherment, the reading, and a status.
status: read = the raw decipherment is the word (i/y/j and diacritics normalised);
        doubt = one or two signs are doubtful on the page and the word is read from sense ([?] in the reading);
        unread = not read."""
import decipher
k = decipher.key()
# (line, raw) -> (reading, status, note)
OV = {
 ('f1r.02', 'dowX.p'): ('do W.X.M.', 'read', 'abbreviation; the M is written with the p-sign 7/ here'),
 ('f1r.03', 'czeęsto'): ('często [?]', 'doubt', 'one extra 8 read before 8^'),
 ('f1r.05', 'poteznie'): ('potężnie [?]', 'doubt', 'signs 4/ and t.8/ unclear, a colon-like mark inside the word'),
 ('f1r.05', 'nasa'): ('nasa-', 'read', 'one word with the next two: nasadziwszy'),
 ('f1r.05', 'dzi'): ('-dzi-', 'read', ''),
 ('f1r.05', 'wszi'): ('-wszy', 'read', ''),
 ('f1r.11', 'srzetelnie'): ('rzetelnie [?]', 'doubt', 'small stroke before 6^ read as +'),
 ('f1r.13', 'pospeieciba'): ('[pospeieci]ba-', 'unread', 'not read: p-o-s-p-e-i-e-c-i before -ba; the 1 is small'),
 ('f1r.14', 'czic'): ('-czyć', 'read', 'end of (o)baczyć? with the word before'),
 ('f1r.17', 'wielkiemi'): ('wielkie[y?]', 'doubt', 'sign read 7^ probably 4'),
 ('f1r.19', 'wbron'): ('(w[?] broń', 'doubt', 'first sign t0/+0 unclear; "broń Boże"'),
 ('f1r.20', 'tw'): ('tu [?]', 'doubt', 't0 or +0'),
 ('f1r.21', 'takobt'): ('iakoby [?]', 'doubt', 'first and last signs read 4/ for 4'),
 ('f1r.23', 'iawen'): ('iawne [?]', 'doubt', 'last two signs in the other order on the page or misread'),
 ('f1r.28', 'panskiez'): ('pańskiey [?]', 'doubt', 'last two signs 4/ 8 t read for 4 8 4'),
 ('f1r.26', 'izmurow'): ('i z murów', 'read', ''),
 ('f1r.34', 'godzina'): ('godzinę [?]', 'doubt', 'last sign 9 for 8^?'),
 ('f1r.34', 'zgininnia'): ('zginienia [?]', 'doubt', 'one 8/ read for 8'),
 ('f1r.35', 'peweni'): ('pewney [?]', 'doubt', 'signs 8 8/ 4 read in the order e-n-i'),
}
rows = ['line\tword\tsigns\traw\tstatus\treading\tnote']
for ref, ws in decipher.lines():
    for i, w in enumerate(ws, 1):
        r = decipher.raw(w, k)
        rd, st, note = OV.get((ref, r), (r, 'read', ''))
        rows.append(f'{ref}\t{i}\t{w}\t{r}\t{st}\t{rd}\t{note}')
open('reading.tsv', 'w', encoding='utf-8').write('\n'.join(rows) + '\n')
print(len(rows) - 1, 'words')

# validation.tsv for docs/_validate.py: one sign per line with the letter it carries; doubtful and unread words '?'
v = ['# model: pl-1790', '# source: transcription.txt + key.tsv, read words from reading.tsv',
     '# note: D (the X of W.X.Mci) carries x; doubtful and unread words left out']
for r in rows[1:]:
    ref, i, w, raw, st = r.split('\t')[:5]
    for s in decipher.signs(w):
        val = 'x' if s == 'D' else k[s]
        v.append(f'{s}\t{val if st == "read" else "?"}')
open('validation.tsv', 'w', encoding='utf-8').write('\n'.join(v) + '\n')

# signs.txt: the transcription as one space-separated sign per item, a line per page line (for --measure)
open('signs.txt', 'w', encoding='utf-8').write(
    '# signs of transcription.txt, one per item (generated by make_reading.py)\n' +
    '\n'.join(' '.join(s for w in ws for s in decipher.signs(w)) for ref, ws in decipher.lines()) + '\n')
