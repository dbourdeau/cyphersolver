V = {}
for w in VOC: V.setdefault(str(val(w)), []).append(w)
def seg(s, i=0, acc=()):
    if i == len(s): yield acc; return
    for L in (1,2,3,4):
        t = s[i:i+L]
        if len(t)==L and t in V: yield from seg(s, i+L, acc+(t,))
