# Decode the transcribed type A runs of Hann. 9g Nr. 1687 (frozen/1687/transcr/) with key.tsv (sure + probable rows only).
# Usage: python targets/diede1730/decode1687.py > targets/diede1730/decryption-1687.txt
# Added at integration (11 Nov 2026). Raw output: one line per cipher line, "?" = group outside the key or doubtful row.
import sys, glob, re, os
d = os.path.dirname(os.path.abspath(__file__))
key = {}
for ln in open(os.path.join(d, 'key.tsv'), encoding='utf-8'):
    if ln.startswith('#') or not ln.strip():
        continue
    c, v, st = ln.rstrip('\n').split('\t')[:3]
    if st in ('sure', 'probable'):
        key[c] = '' if v == '·' else v
tot = hit = 0
print('# diede1730 - raw decode of the transcribed type A runs of Hann. 9g Nr. 1687 with key.tsv (sure + probable rows).')
print('# Generated by decode1687.py. "?" = group outside the key or on a doubtful row. Decoded, not read: no word-by-word')
print('# check has been made on these runs, except the samples quoted in NOTES.md (aufn 027, 033-036, 056).')
for f in sorted(glob.glob(os.path.join(d, 'frozen', '1687', 'transcr', '1687_*.txt'))):
    aufn = os.path.basename(f)[5:8]
    print(f'\n## aufn {aufn}')
    for ln in open(f, encoding='utf-8'):
        m = re.match(r'^([RL]\d+)\s+\S+\s+([\d.?]+)', ln)
        if not m:
            continue
        s = ''
        for g in m.group(2).split('.'):
            g = g.strip('?')
            if not g.isdigit():
                continue
            tot += 1
            if g in key:
                hit += 1
                s += key[g]
            else:
                s += '?'
        print(f'{m.group(1)}\t{s}')
print(f'\n# groups {tot}, with a sure/probable key value {hit}')
