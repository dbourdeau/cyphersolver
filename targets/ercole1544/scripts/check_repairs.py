#!/usr/bin/env python3
"""Check each reading against its decryption, letter by letter. Standard library only.

    python check_repairs.py           list departures from the signs that are not marked; exit 1 if any
    python check_repairs.py --table   also write editorial_<doc>.md, the table of marked repairs

Unmarked word = verbatim from the signs. word° = repair (the table gives the signs). [?word] = proposal, [...] = unread,
[L^30], [43] = code not identified. u/v and i/j are one letter; spaces and punctuation are not compared.
"""
import difflib, os, re, sys
os.chdir(os.path.dirname(os.path.abspath(__file__)) if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'key.tsv'))
         else os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EXP = {'VOSTRA EXCELLENTIA': 'vostraexcellentia', 'PAPA': 'papa', 'FRANCIA': 'francia', 'FRANCESI': 'francesi', 'ITALIA': 'italia'}
DOCS = ('0078_0079', '0174_0175')
HEAD = '''# Editorial repairs, {doc}

Generated by `check_repairs.py --table`. Each row is a place where a word marked with a degree sign departs from the letters the signs give.
Brackets hold what the signs give there; empty brackets mean the reading has a letter the signs lack. Line labels refer to the transcription.

| line | reading | the signs give |
|---|---|---|
'''


def norm(s):
    return s.lower().replace('v', 'u').replace('j', 'i').replace('à', 'a')


def dec(path):
    out = []
    for l in open(path, encoding='utf8'):
        lab, _, b = l.strip().partition(' ')
        def r(m):
            k = m.group(1)
            if k[0] in '#?': return '~'
            return EXP.get(k, k.lower().replace(' ', ''))
        b = re.sub(r'\[([^\]]+)\]', r, b.replace('.', '')).replace('?', '~')
        out.append((lab, norm(b)))
    return out


def rd(path):
    """Letters of the reading; for each letter the word it belongs to and whether that word carries the mark."""
    letters, word, marked = [], [], []
    for lab, txt in re.findall(r'^IT\[([^\]]+)\]: (.*)$', open(path, encoding='utf8').read(), re.M):
        txt = re.sub(r'\[[^\]]*\]', ' ~ ', txt)
        for tok in txt.split():
            m = '°' in tok
            for piece in tok.replace("'", ' ').split():
                for c in norm(piece):
                    if c.isalpha() or c == '~':
                        letters.append(c); word.append(piece.strip('.,;:')); marked.append(m and '°' in piece or (m and "'" not in tok))
    return ''.join(letters), word, marked


def main():
    bad = 0
    for doc in DOCS:
        D = dec(f'decryption_{doc}.txt')
        ds = ''.join(b for _, b in D); pos = []
        for lab, b in D: pos += [lab] * len(b)
        rs, word, marked = rd(f'reading_{doc}.md')
        rows = []
        for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, ds, rs, autojunk=False).get_opcodes():
            if op == 'equal': continue
            a, b = ds[i1:i2], rs[j1:j2]
            if '~' in b: continue
            if op == 'delete' and '~' in rs[max(0, j1 - 1):j1 + 1]: continue
            if a.replace('~', '') == '' and not b: continue
            near = [k for k in range(max(0, j1 - 1), min(len(rs), j2 + 1)) if marked[k]]
            lab = pos[min(i1, len(pos) - 1)]
            if not near:
                bad += 1
                print(lab, repr(ds[max(0, i1 - 10):i1]), 'signs', repr(a), 'reading', repr(b), repr(rs[j2:j2 + 10]))
            else:
                k = near[0] if j1 >= len(word) else (j1 if marked[min(j1, len(rs) - 1)] else near[0])
                rows.append((lab, word[k], ds[max(0, i1 - 7):i1] + '[' + a + ']' + ds[i2:i2 + 7]))
        if '--table' in sys.argv:
            with open(f'editorial_{doc}.md', 'w', encoding='utf8', newline='\n') as f:
                f.write(HEAD.format(doc=doc))
                for lab, w, s in rows:
                    f.write(f'| {lab} | {w} | `{s}` |\n')
        print(doc, 'marked departures', len(rows))
    print('unmarked differences', bad)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
