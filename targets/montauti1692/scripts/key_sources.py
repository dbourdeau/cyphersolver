"""List the source of every key value: each group, its letter, which frozen key holds it, and every place in
Oversize Ms. Codex 534 where the recipient's interlinear letter stands over it (folio, line or segment, word).

usage (from the target folder): python scripts/key_sources.py > key/key_entries.tsv

Inputs, all in this folder:
  key/pairs_534_f14r_f15r.tsv   f. 14r lines 1-14 and f. 15r lines 5-6 (the build pairs of keys v1 and v2)
  test/heldout_534_f15r.tsv     f. 15r held-out pairs of the round-2 test (folded into key v2 afterwards)
  test/heldout_21r_cipher.tsv + test/heldout_21r_interline.tsv   f. 21r, the round-3 held-out test (source of 91 = u)
  key/pairs_534_f396v.tsv       f. 396v line 2 (source of w6 = i)
  key/key_v1.json, key_v2.json, key_v3.json, key_v3_context.json
"""
import json, re, collections, difflib

def load(fn):
    return {k: v for k, v in json.load(open(fn, encoding='utf-8')).items() if not k.startswith('_')}

k1, k2, k3, kc = (load('key/' + f) for f in ('key_v1.json', 'key_v2.json', 'key_v3.json', 'key_v3_context.json'))
att = collections.defaultdict(list)   # (group, letter) -> [source]

# f. 14r and f. 15r build pairs
for l in open('key/pairs_534_f14r_f15r.tsv', encoding='utf-8'):
    if l.startswith('#') or l.startswith('line'):
        continue
    c = l.rstrip('\n').split('\t')
    if len(c) < 5:
        continue
    line, ctx, groups, letters, word = c[:5]
    g = groups.split(); t = letters.split()
    if len(g) != len(t):
        continue
    m = re.match(r'(\d+)\s*\((\d+[rv])\)', line.strip())
    if m:
        fol, ln = m.group(2), m.group(1)
    elif line.startswith('15r-'):
        fol, ln = '15r', line.split('-')[1]
    else:
        fol, ln = '14r', line.strip()
    w = word.split('(')[0].strip()
    for a, b in zip(g, t):
        att[(a, b)].append(f'534 f.{fol} l.{ln} "{w}"')

# f. 15r held-out pairs (round-2 test), single groups
for l in open('test/heldout_534_f15r.tsv', encoding='utf-8'):
    if l.startswith('#') or l.startswith('seg'):
        continue
    c = l.rstrip('\n').split('\t')
    if len(c) >= 4 and c[3] not in ('?', '') and len(c[3]) == 1:
        att[(c[2], c[3])].append(f'534 f.15r seg.{c[0]} (held-out, round 2)')

# f. 21r held-out (round 3): aligned decode vs interline, record only groups the frozen key v2 lacked
ct = {}
for l in open('test/heldout_21r_cipher.tsv', encoding='utf-8'):
    if l.startswith('#') or l.startswith('seg'):
        continue
    s, _, sig = l.rstrip('\n').split('\t'); ct[s] = sig.split()
for l in open('test/heldout_21r_interline.tsv', encoding='utf-8'):
    if l.startswith('#') or l.startswith('seg'):
        continue
    s, t = l.rstrip('\n').split('\t')
    x = ct[s]
    best = None
    for off in (0, 1):
        p = [x[i] + x[i + 1] for i in range(off, len(x) - 1, 2)]
        h = sum(g in k2 for g in p)
        if best is None or h > best[0]:
            best = (h, p)
    p = best[1]
    dec = ''.join(k2.get(g, '#') for g in p)
    sm = difflib.SequenceMatcher(None, dec, t, autojunk=False)
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == 'replace' and i2 - i1 == j2 - j1:
            for i, j in zip(range(i1, i2), range(j1, j2)):
                if dec[i] == '#' and p[i] == '91':
                    att[('91', 'u')].append(f'534 f.21r seg.{s} "{t}" (after the round-3 test)')

# f. 396v (round 4)
att[('w6', 'i')].append('534 f.396v l.2 "la minaccia" (one attestation; sign separation uncertain)')

print('# Key entries of the Grand Duke\'s letter cipher (System B), with the source of each value. Generated by scripts/key_sources.py.')
print('# key: v1 = key_v1.json (f. 14r only), v2 = key_v2.json, v3 = key_v3.json (v2 + w6, 91), context = key_v3_context.json (NOT attested under any interline).')
print('# sources: 534 = University of Pennsylvania Oversize Ms. Codex 534; the letter is the recipient\'s interlinear decipherment over that group.')
print('group\tletter\tfirst_key\tn_interline\tsources')
allg = dict(k3); allg.update(kc)
for g in sorted(allg):
    v = allg[g]
    first = 'v1' if g in k1 else 'v2' if g in k2 else 'v3' if g in k3 else 'context'
    src = att.get((g, v), [])
    if first == 'context':
        note = {'ww': 'context only: 14 places in the bare 534 passages ff. 114r-116r and 11 in Codex 533, o every time; no interline',
                '62': 'context only: 3 places in Codex 533 ("ritornare qua" 1r, "qualche facilità" 63r, "qu..." 25r); fits the table order 60 p, 62 q, 64 r; no interline'}[g]
        src = [note]
    print(f'{g}\t{v}\t{first}\t{0 if first == "context" else len(src)}\t' + '; '.join(src))
