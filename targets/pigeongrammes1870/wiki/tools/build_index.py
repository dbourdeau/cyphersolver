"""Rebuild index.md (the catalogue) from the pages' front matter. Run after every ingest or loop."""
import os,sys,collections,re
import wikilib as W
sys.stdout.reconfigure(encoding="utf8")
P=W.pages()
order=["established","supported","hypothesis","open","rejected"]
lines=["# Index","","Catalogue of the wiki (generated by `tools/build_index.py`). Read `SCHEMA.md` and `PROCESS.md` first; the log is `log.md`.",""]
lex=W.load_lex("inspectors")["entries"]; fav=W.load_lex("favre")["entries"]
acc=[e for e in lex if e["status"] in ("supported","established")]
lines+=["## State of knowledge","",
 "- Inspectors' lexicon: %d entries, %d accepted (supported/established), %d auto-accepted by the engine."%(len(lex),len(acc),sum(1 for e in lex if e.get("auto")=="true")),
 "- Favre/delegation lexicon: %d entries, %d accepted."%(len(fav),sum(1 for e in fav if e["status"] in ("supported","established"))),
 "- Claims by status: "+", ".join("%s %d"%(s,sum(1 for k,(fm,b,p) in P.items() if fm and fm.get("type")=="claim" and fm.get("status")==s)) for s in order),
 "- Open questions: %d"%sum(1 for k,(fm,b,p) in P.items() if fm and fm.get("type")=="question" and fm.get("status")=="open"),""]
def summ(body):
    first=body.strip().split(chr(10))[0] if body.strip() else ""
    t=re.sub(r"\[\[([A-Z]\d+)\]\]",lambda m:m.group(1),first)
    t=re.sub(r"[`*]","",t)
    return (t[:150]+"...") if len(t)>150 else t
def section(title,typ,extra=None):
    items=[(k,fm) for k,(fm,b,p) in P.items() if fm and fm.get("type")==typ]
    lines.append("## %s (%d)"%(title,len(items))); lines.append("")
    if typ=="claim":
        for s in order:
            for k,fm in items:
                if fm.get("status")==s: lines.append("- [[%s]] **%s** (%s) %s: %s"%(k,s,fm.get("confidence"),fm["title"],summ(P[k][1])))
    else:
        for k,fm in items: lines.append("- [[%s]] %s: %s"%(k,fm["title"],summ(P[k][1])))
    lines.append("")
section("Syntheses","synthesis"); section("Sources","source"); section("Entities","entity"); section("Systems","system"); section("Claims","claim"); section("Questions","question"); section("Tests","test")
open(os.path.join(W.ROOT,"index.md"),"w",encoding="utf8").write("\n".join(lines))
print("index.md rebuilt:",len(P),"pages")
